#!/usr/bin/env python3
"""Copy Android's exact symbol assets/catalog from a pinned Git ref.

No image processing: iOS applies Android's transparency/night rules at runtime.
"""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

android = Path(sys.argv[1] if len(sys.argv) > 1 else '../gridfix').resolve()
ref = sys.argv[2] if len(sys.argv) > 2 else 'origin/release/1.1.0'
root = Path(__file__).resolve().parent.parent

def git(*args):
    return subprocess.check_output(['git', '-C', str(android), *args])

def source(path):
    return git('show', ref + ':' + path).decode()

base = 'app/src/main/java/app/gridfix/android/ui/'
nato = source(base + 'NatoSymbols.kt')
pairs = []
for variable in ['functions', 'extended']:
    body = re.search(r'val ' + variable + r'\b[^=]*= listOf\((.*?)\n    \)', nato, re.S).group(1)
    pairs.extend(re.findall(r'"([a-z0-9_]+)" to "([^"]+)"', body))
assert len(pairs) == 124 and len(dict(pairs)) == 124
basic = [('dot','Dot'),('triangle','Triangle'),('square','Square'),('diamond','Diamond'),('cross','Cross'),('flag','Flag'),('target','Target'),('star','Star'),('home','Home'),('danger','Danger'),('water','Water'),('camp','Camp'),('vehicle','Vehicle'),('antenna','Antenna'),('medic','Medic')]
waypoint = source(base + 'WaypointSymbols.kt')
body = re.search(r'fun taskLabel.*?when \(key\) \{(.*?)else ->', waypoint, re.S).group(1)
tasks = re.findall(r'"(task_[a-z]+)" -> "([^"]+)"', body)
assert len(tasks) == 20
out = root / 'App/Resources/MilitarySymbols'
out.mkdir(parents=True, exist_ok=True)
manifest = {'source': 'Artemis2028/gridfix', 'commit': git('rev-parse', ref).decode().strip(), 'files': {}}
for function, _ in pairs:
    for affiliation in 'fhnu':
        name = f'nato_{affiliation}_{function}.png'
        data = git('show', ref + ':app/src/main/res/drawable-nodpi/' + name)
        assert data.startswith(b'\x89PNG\r\n\x1a\n')
        (out / name).write_bytes(data)
        manifest['files'][name] = hashlib.sha256(data).hexdigest()
(out / 'military-symbol-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
(out / 'Android-MIT-LICENSE.txt').write_bytes(git('show', ref + ':LICENSE'))
(out / 'android-symbol-codes.tsv').write_bytes(git('show', ref + ':app/symbol-manifest.tsv'))
(out / 'MilitarySymbols-README.txt').write_text('Exact Android GridFix release/1.1.0 MIL-STD-2525B land-unit PNGs.\nSee military-symbol-manifest.json for source commit and SHA-256 values.\nThe catalog is the Android app\'s curated set, not every symbol in MIL-STD-2525.\nRuntime applies the same black-pixel transparency and red night transform.\n')

def swift_entries(items):
    return '\n'.join('        .init(key: '+json.dumps(k)+', label: '+json.dumps(v, ensure_ascii=False)+'),' for k, v in items)
text = '''import Foundation

/// Exact symbol keys/labels from Android release/1.1.0, generated by
/// scripts/ImportAndroidSymbols.py. The curated unit set has 124 functions × 4.
public enum MilitarySymbols {
    public struct Entry: Equatable, Sendable, Identifiable {
        public let key: String
        public let label: String
        public var id: String { key }
    }
    public static let functions: [Entry] = [
FUNCTIONS
    ]
    public static let basic: [Entry] = [
BASIC
    ]
    public static let tasks: [Entry] = [
TASKS
    ]
    public static let affiliations: [Entry] = [.init(key: "none",label: "None"),.init(key: "friendly",label: "Friendly"),.init(key: "hostile",label: "Hostile"),.init(key: "neutral",label: "Neutral"),.init(key: "unknown",label: "Unknown")]
    public static let echelons: [Entry] = [.init(key: "",label: "None"),.init(key: "tm",label: "Team"),.init(key: "sqd",label: "Squad"),.init(key: "sec",label: "Section"),.init(key: "plt",label: "Platoon"),.init(key: "co",label: "Company"),.init(key: "bn",label: "Battalion"),.init(key: "rgt",label: "Regiment"),.init(key: "bde",label: "Brigade"),.init(key: "div",label: "Division"),.init(key: "corps",label: "Corps"),.init(key: "army",label: "Army")]
    public static var unitKeys: [String] { ["f","h","n","u"].flatMap { aff in functions.map { "nato_\\(aff)_\\($0.key)" } } }
    public static func function(_ key: String) -> String? {
        guard key.hasPrefix("nato_") else { return nil }
        let parts = key.split(separator: "_",maxSplits: 2)
        return parts.count == 3 ? String(parts[2]) : nil
    }
    public static func affiliationCode(_ affiliation: String) -> String {
        switch affiliation { case "hostile": return "h"; case "neutral": return "n"; case "unknown": return "u"; default: return "f" }
    }
    public static func label(_ key: String) -> String {
        if let function = function(key) {
            let aff = key.split(separator: "_")[1]
            let name = ["f":"Friendly","h":"Hostile","n":"Neutral","u":"Unknown"][String(aff)] ?? String(aff)
            return name + " " + (functions.first { $0.key == function }?.label ?? function)
        }
        return (basic + tasks).first { $0.key == key }?.label ?? key
    }
}
'''.replace('FUNCTIONS', swift_entries(pairs)).replace('BASIC', swift_entries(basic)).replace('TASKS', swift_entries(tasks))
(root / 'GridFixCore/Sources/GridFixCore/MilitarySymbols.swift').write_text(text)
print(f'Imported {len(manifest["files"])} exact unit images, {len(tasks)} task keys, {len(basic)} basic keys')
